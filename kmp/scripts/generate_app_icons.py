"""Generate SVG, Compose paths and iOS template vectors from design/icons/icons.json."""
from pathlib import Path
import json
from xml.sax.saxutils import quoteattr
from icon_overrides import apply_overrides

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'design/icons'
registry = json.loads((ASSETS/'icons.json').read_text())
apply_overrides(registry)
(ASSETS/'icons.json').write_text(json.dumps(registry,ensure_ascii=False,indent=2)+'\n')
svg_dir = ASSETS/'svg'; svg_dir.mkdir(exist_ok=True)

def styles(icon):
    return icon.get('pathStyles', [dict(fill=icon['filled'],strokeWidth=registry['stroke']) for _ in icon['paths']])

def svg_paths(icon, color='currentColor'):
    return ''.join('<path d='+quoteattr(d)+' fill="'+(color if style['fill'] else 'none')+'" stroke="'+(color if style['strokeWidth'] else 'none')+'" stroke-width="'+str(style['strokeWidth'])+'" stroke-linecap="round" stroke-linejoin="round"/>' for d,style in zip(icon['paths'],styles(icon)))

def svg(icon, color='currentColor'):
    return '<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24">'+svg_paths(icon,color)+'</svg>\n'

lines=['// Generated by scripts/generate_app_icons.py; edit design/icons/icons.json.',
'package com.aiweapps.winescan.components','',
'import androidx.compose.ui.graphics.Color','import androidx.compose.ui.graphics.SolidColor',
'import androidx.compose.ui.graphics.StrokeCap','import androidx.compose.ui.graphics.StrokeJoin',
'import androidx.compose.ui.graphics.vector.ImageVector','import androidx.compose.ui.graphics.vector.PathParser',
'import androidx.compose.ui.unit.dp','',
'/** Figma v3 outlines retain their exported filled contours; colors belong to the caller. */',
'internal object AppIcons {']
for name,icon in registry['icons'].items():
    (svg_dir/(name+'.svg')).write_text(svg(icon))
    args=', '.join('IconPath('+json.dumps(d)+', '+str(style['fill']).lower()+', '+str(style['strokeWidth'])+'f)' for d,style in zip(icon['paths'],styles(icon)))
    lines.append(f'    val {name}: ImageVector by lazy {{ icon("{name}", {str(icon["autoMirror"]).lower()}, {args}) }}')
lines+=['', '    private data class IconPath(val data: String, val filled: Boolean, val strokeWidth: Float)',
'    private fun icon(name: String, mirrored: Boolean, vararg paths: IconPath): ImageVector =',
'        ImageVector.Builder(name, 24.dp, 24.dp, 24f, 24f, autoMirror = mirrored).apply {',
'            paths.forEach { path ->', '                addPath(',
'                    pathData = PathParser().parsePathString(path.data).toNodes(),',
'                    fill = if (path.filled) SolidColor(Color.Black) else null,',
'                    stroke = if (path.strokeWidth > 0) SolidColor(Color.Black) else null,',
'                    strokeLineWidth = path.strokeWidth,',
'                    strokeLineCap = StrokeCap.Round,','                    strokeLineJoin = StrokeJoin.Round,',
'                )','            }','        }.build()','}']
(ROOT/'androidApp/src/main/kotlin/com/aiweapps/winescan/components/AppIcons.kt').write_text('\n'.join(lines)+'\n')
for filename,concept in [('ic_wine_discovery','Wine'),('ic_new_conversation','NewChat')]:
    icon=registry['icons'][concept]
    paths='\n'.join('    <path android:pathData='+quoteattr(d)+' android:fillColor="'+('#FF000000' if style['fill'] else '#00000000')+'" android:strokeColor="'+('#FF000000' if style['strokeWidth'] else '#00000000')+'" android:strokeWidth="'+str(style['strokeWidth'])+'" android:strokeLineCap="round" android:strokeLineJoin="round" />' for d,style in zip(icon['paths'],styles(icon)))
    (ROOT/f'androidApp/src/main/res/drawable/{filename}.xml').write_text('<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="24dp" android:height="24dp" android:viewportWidth="24" android:viewportHeight="24">\n'+paths+'\n</vector>\n')
for concept, icon in registry['icons'].items():
    asset='app_icon_'+concept.lower()
    target=ROOT/f'iosApp/iosApp/Assets.xcassets/{asset}.imageset';target.mkdir(exist_ok=True)
    (target/(asset+'.svg')).write_text(svg(icon,'#000000'))
    (target/'Contents.json').write_text(json.dumps(dict(images=[dict(filename=asset+'.svg',idiom='universal')],info=dict(author='xcode',version=1),properties={'preserves-vector-representation':True,'template-rendering-intent':'template'}),indent=2)+'\n')
# Existing brand menu consumers use the exact same geometry.
target=ROOT/'iosApp/iosApp/Assets.xcassets/navigation_menu.imageset'
(target/'navigation_menu.svg').write_text(svg(registry['icons']['Menu'],'#000000'))
print(f"Exported {len(registry['icons'])} native concepts for Android and iOS")
